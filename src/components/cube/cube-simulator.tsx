"use client";
import dynamic from "next/dynamic";
import { useCallback, useEffect, useRef, useState } from "react";
import { Play, Pause, SkipForward, SkipBack, RotateCcw, Shuffle, Keyboard, CheckCircle2, Loader2 } from "lucide-react";
import type { CubeHandle } from "./cube3d";
import { applyAlg, applyMove, invertMoves, isSolved, normalizeToCenters, parseAlg, ParsedMove, randomMoveScramble, SOLVED } from "@/lib/cube/model";
import { validateFacelets } from "@/lib/cube/validate";
import { initSolver, randomStateScramble, solveFacelets } from "@/lib/cube/solver-client";
import { CubeNet } from "./cube-net";

const Cube3D = dynamic(() => import("./cube3d").then((m) => m.Cube3D), { ssr: false, loading: () => <div className="h-full grid place-items-center text-muted text-sm"><Loader2 className="animate-spin" /> Loading 3D cube…</div> });

type Kind = "manual" | "fwd" | "back";
export interface Sequence { label: string; moves: ParsedMove[]; startState: string }

const MOVE_ROWS = [["U", "D", "R", "L", "F", "B"], ["M", "E", "S", "x", "y", "z"]];

export function CubeSimulator({ initialState = SOLVED, initialSequence, compact, onSolvedChange }: { initialState?: string; initialSequence?: Sequence | null; compact?: boolean; onSolvedChange?: (s: boolean) => void }) {
  const cube = useRef<CubeHandle>(null);
  const [state, setState] = useState(initialState);
  const stateRef = useRef(initialState);
  const [seq, setSeq] = useState<Sequence | null>(initialSequence ?? null);
  const [pos, setPos] = useState(0);
  const kinds = useRef<Kind[]>([]);
  const [busy, setBusy] = useState(false);
  const [speed, setSpeed] = useState(4);
  const [algText, setAlgText] = useState("");
  const [msg, setMsg] = useState<{ kind: "error" | "info"; text: string } | null>(null);
  const [solverState, setSolverState] = useState<"idle" | "loading" | "ready" | "error">("idle");
  const [scramble, setScramble] = useState<string | null>(null);
  const [working, setWorking] = useState(false);

  useEffect(() => { onSolvedChange?.(isSolved(state)); }, [state, onSolvedChange]);

  const warmSolver = useCallback(() => {
    if (solverState !== "idle") return;
    setSolverState("loading");
    initSolver().then(() => setSolverState("ready")).catch(() => setSolverState("error"));
  }, [solverState]);

  const enqueue = useCallback((moves: ParsedMove[], kind: Kind) => {
    if (!moves.length) return;
    kinds.current.push(...moves.map(() => kind));
    cube.current?.enqueue(moves);
    setBusy(true);
  }, []);

  const onMoveDone = useCallback((m: ParsedMove) => {
    const kind = kinds.current.shift();
    stateRef.current = applyMove(stateRef.current, m);
    setState(stateRef.current);
    if (kind === "fwd") setPos((p) => p + 1);
    if (kind === "back") setPos((p) => p - 1);
  }, []);
  const onIdle = useCallback(() => setBusy(false), []);

  const hardReset = useCallback((s: string) => {
    cube.current?.reset(s);
    kinds.current = [];
    stateRef.current = s;
    setState(s);
    setBusy(false);
  }, []);

  const manual = useCallback((text: string) => {
    if (seq) { setSeq(null); setPos(0); }
    enqueue(parseAlg(text), "manual");
  }, [enqueue, seq]);

  // keyboard notation
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      const t = e.target as HTMLElement;
      if (t && (t.tagName === "INPUT" || t.tagName === "TEXTAREA" || t.isContentEditable)) return;
      if (e.metaKey || e.ctrlKey || e.altKey) return;
      const k = e.key.toUpperCase();
      if (!"URFDLBMESXYZ".includes(k) || k.length !== 1) return;
      e.preventDefault();
      const base = "XYZ".includes(k) ? k.toLowerCase() : k;
      manual(base + (e.shiftKey ? "'" : ""));
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [manual]);

  const play = () => { if (!seq) return; enqueue(seq.moves.slice(pos), "fwd"); };
  const pause = () => { const inflight = cube.current?.clearQueue() ?? 0; kinds.current = kinds.current.slice(0, inflight); if (!inflight) setBusy(false); };
  const stepF = () => { if (seq && !busy && pos < seq.moves.length) enqueue([seq.moves[pos]], "fwd"); };
  const stepB = () => { if (seq && !busy && pos > 0) enqueue(invertMoves([seq.moves[pos - 1]]), "back"); };
  const restartSeq = () => { if (!seq) return; hardReset(seq.startState); setPos(0); };

  const doScramble = async () => {
    setMsg(null); setWorking(true); setSeq(null); setPos(0);
    try {
      setSolverState((s) => (s === "ready" ? s : "loading"));
      const r = await randomStateScramble();
      setSolverState("ready");
      setScramble(r.scramble);
      hardReset(applyAlg(SOLVED, r.scramble));
      setMsg({ kind: "info", text: "Random-state scramble (WCA style) generated by the two-phase solver." });
    } catch {
      const s = randomMoveScramble(25);
      setScramble(s);
      hardReset(applyAlg(SOLVED, s));
      setMsg({ kind: "info", text: "Solver unavailable — used a 25-move random-move scramble instead." });
    } finally { setWorking(false); }
  };

  const doSolve = async () => {
    setMsg(null);
    if (busy) return;
    const norm = normalizeToCenters(stateRef.current);
    const v = validateFacelets(norm);
    if (!v.ok) { setMsg({ kind: "error", text: v.errors.join(" ") }); return; }
    if (isSolved(norm)) { setMsg({ kind: "info", text: "The cube is already solved." }); return; }
    setWorking(true);
    try {
      setSolverState((s) => (s === "ready" ? s : "loading"));
      const t0 = performance.now();
      const sol = await solveFacelets(norm);
      setSolverState("ready");
      const moves = parseAlg(sol);
      // double-check the solver output with our own model before showing it
      if (!isSolved(applyAlg(stateRef.current, moves))) throw new Error("Solver output failed verification");
      setSeq({ label: `Solution (${moves.length} moves, Kociemba two-phase)`, moves, startState: stateRef.current });
      setPos(0);
      setMsg({ kind: "info", text: `Solved in ${Math.round(performance.now() - t0)} ms and verified. Press play or step through it.` });
    } catch (e) {
      setSolverState("error");
      setMsg({ kind: "error", text: `Solver error: ${(e as Error).message}` });
    } finally { setWorking(false); }
  };

  const doApplyAlg = () => {
    setMsg(null);
    try {
      const moves = parseAlg(algText);
      if (!moves.length) return;
      setSeq({ label: "Algorithm", moves, startState: stateRef.current });
      setPos(0);
      kinds.current.push(...moves.map(() => "fwd" as Kind));
      cube.current?.enqueue(moves);
      setBusy(true);
    } catch (e) { setMsg({ kind: "error", text: (e as Error).message }); }
  };

  const solved = isSolved(state);

  return (
    <div className={`grid gap-6 ${compact ? "" : "lg:grid-cols-[1.4fr_1fr]"}`}>
      <div className="card relative overflow-hidden">
        <div className="absolute top-3 left-3 z-10 flex gap-2 flex-wrap">
          {solved ? <span className="chip !text-ok !border-ok bg-surface"><CheckCircle2 size={12} /> Solved</span> : <span className="chip bg-surface">Scrambled</span>}
          {solverState === "loading" && <span className="chip bg-surface"><Loader2 size={12} className="animate-spin" /> Building solver tables…</span>}
        </div>
        <Cube3D ref={cube} initialState={initialState} speed={speed} onMoveDone={onMoveDone} onIdle={onIdle} className={compact ? "h-[340px]" : "h-[380px] sm:h-[460px]"} />
        {seq && (
          <div className="border-t border-line p-4 bg-surface">
            <div className="text-xs text-muted mb-2 font-mono">{seq.label} · step {pos}/{seq.moves.length}</div>
            <div className="flex flex-wrap gap-1 mb-3 max-h-24 overflow-y-auto">
              {seq.moves.map((m, i) => (
                <span key={i} className={`font-mono text-[13px] px-1 ${i < pos ? "text-muted" : ""} ${i === pos ? "bg-cube text-bg" : ""}`}>{m.text}</span>
              ))}
            </div>
            <div className="flex flex-wrap gap-2">
              <button className="btn btn-ghost" onClick={restartSeq} disabled={busy} aria-label="Restart"><RotateCcw size={16} /></button>
              <button className="btn btn-ghost" onClick={stepB} disabled={busy || pos === 0} aria-label="Step back"><SkipBack size={16} /></button>
              {busy ? <button className="btn btn-primary" onClick={pause}><Pause size={16} /> Pause</button>
                : <button className="btn btn-primary" onClick={play} disabled={pos >= seq.moves.length}><Play size={16} /> Play</button>}
              <button className="btn btn-ghost" onClick={stepF} disabled={busy || pos >= seq.moves.length} aria-label="Step forward"><SkipForward size={16} /></button>
            </div>
          </div>
        )}
      </div>

      <div className="space-y-4">
        <div className="card p-4">
          <div className="flex items-center justify-between mb-3"><h3 className="eyebrow">Turn the cube</h3><span className="text-xs text-muted inline-flex items-center gap-1.5"><Keyboard size={13} aria-hidden /> Keyboard: <kbd className="font-mono">U R F D L B M E S X Y Z</kbd>, Shift for prime</span></div>
          {MOVE_ROWS.map((row, ri) => (
            <div key={ri} className="grid grid-cols-6 gap-1.5 mb-1.5">
              {row.map((b) => (
                <div key={b} className="grid grid-rows-3 gap-1">
                  {[b, b + "'", b + "2"].map((m) => (
                    <button key={m} onClick={() => manual(m)} className="rounded-sm border border-line py-1 text-xs font-mono hover:border-fg hover:bg-surface-2">{m}</button>
                  ))}
                </div>
              ))}
            </div>
          ))}
          <div className="flex items-center gap-3 mt-3 text-sm">
            <label htmlFor="speed" className="text-muted">Speed</label>
            <input id="speed" type="range" min={1} max={12} value={speed} onChange={(e) => setSpeed(+e.target.value)} className="flex-1 accent-[var(--blue)]" />
            <span className="w-14 text-right font-mono text-xs">{speed} tps</span>
          </div>
        </div>
        <div className="card p-4 space-y-3" onMouseEnter={warmSolver}>
          <div className="grid grid-cols-3 gap-2">
            <button className="btn btn-ghost" onClick={doScramble} disabled={busy || working}><Shuffle size={16} /> Scramble</button>
            <button className="btn btn-primary" onClick={doSolve} disabled={busy || working}>{working && <Loader2 size={16} className="animate-spin" />} Solve</button>
            <button className="btn btn-ghost" onClick={() => { setSeq(null); setScramble(null); hardReset(SOLVED); setMsg(null); }} disabled={working}><RotateCcw size={16} /> Reset</button>
          </div>
          {scramble && <div className="text-xs"><span className="eyebrow mr-2">Scramble</span><span className="font-mono">{scramble}</span></div>}
          <div className="flex gap-2">
            <input className="input font-mono" placeholder="Algorithm, e.g. R U R' U' R' F R2 U' R' U' R U R' F'" value={algText} onChange={(e) => setAlgText(e.target.value)} onKeyDown={(e) => e.key === "Enter" && doApplyAlg()} aria-label="Algorithm" />
            <button className="btn btn-ghost" onClick={doApplyAlg} disabled={busy}>Apply</button>
          </div>
          {msg && <p className={`text-xs ${msg.kind === "error" ? "text-bad" : "text-muted"}`} role={msg.kind === "error" ? "alert" : undefined}>{msg.text}</p>}
        </div>
        {!compact && (
          <div className="card p-4">
            <h3 className="eyebrow mb-3">Cube net</h3>
            <CubeNet state={state} />
          </div>
        )}
      </div>
    </div>
  );
}
